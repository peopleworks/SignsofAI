"""Write Docs/DETECTION.md from the measurement files in Docs/Detection/.

Every number on the page comes from those files. Nothing here is typed by hand, so the page and the
data cannot drift apart: change the measurement, re-run this, and the page follows.
"""

import argparse
import json
from pathlib import Path

NAMES = {
    "chatgpt": "ChatGPT", "gpt4": "GPT-4", "llama-chat": "Llama 2 70B Chat", "mistral-chat": "Mistral 7B Chat",
    "mpt-chat": "MPT-30B Chat", "cohere-chat": "Cohere Chat", "gpt3": "GPT-3 (text-davinci-003)",
    "gpt2": "GPT-2 XL", "mistral": "Mistral 7B", "cohere": "Cohere", "mpt": "MPT-30B",
}
GROUP = {**{m: "chat-tuned" for m in ["chatgpt", "gpt4", "llama-chat", "mistral-chat", "mpt-chat", "cohere-chat"]},
         **{m: "base" for m in ["gpt2", "mistral", "cohere", "mpt"]}, "gpt3": "instruction-tuned"}
DOMAINS = {"abstracts": "arXiv abstracts", "books": "book summaries", "news": "news articles", "poetry": "poetry",
           "recipes": "recipes", "reddit": "Reddit posts", "reviews": "film reviews", "wiki": "Wikipedia"}


def pct(x, digits=1):
    return "n/a" if x is None else f"{x * 100:.{digits}f}%"


def interval(pair):
    lo, hi = pair
    return f"{lo * 100:.1f}–{hi * 100:.1f}%"


def build(r: dict, a: dict, lb: dict, commit: str, run_date: str) -> str:
    s = r["sample"]
    pd_ = r["perDomainThreshold"]
    single = r["singleThreshold"]
    prod = r["product"]
    lh = r["longHumanCheck"]
    groups = pd_["byGroup"]
    by_model = pd_["byModel"]
    rules = {x["rule"]: x for x in r["rules"]}
    attacks = a["attacks"]
    preds = {p["id"]: p for p in r["predictions"]}
    base_models = [by_model[m]["tpr05"] for m in ["gpt2", "mistral", "cohere", "mpt"]]
    burst = rules.get("stat.burstiness")
    poetry_burst = next((x for x in r["domainRules"]["poetry"] if x["rule"] == "stat.burstiness"), None)

    L = []
    w = L.append
    w("# How much machine-written text this tool catches")
    w("")
    w("<!-- Generated by tools/raid/report.py from Docs/Detection/*.json. Do not edit by hand: re-run it. -->")
    w("")
    w("[CALIBRATION.md](CALIBRATION.md) measures how often this tool is wrong about a person, and says plainly what "
      "it leaves out: nothing about how much AI writing it catches, because a tool that flags nothing has a perfect "
      "false-positive rate. This page measures that other half.")
    w("")
    w("The calibration page also says why it avoids an accuracy figure: any collection of machine-written text ages, "
      "and flatters whoever assembled it. So this page uses a collection nobody here assembled, "
      "**RAID** (Dugan et al., ACL 2024, [arXiv 2405.07940](https://arxiv.org/abs/2405.07940)), the largest public "
      "benchmark for detectors of machine-generated text, and it states the date. RAID's generators are from 2023. "
      "The tells this tool looks for shift with every model, so this half of the picture ages and the human half "
      "does not.")
    w("")
    w("## What was measured")
    w("")
    w(f"- **Benchmark** RAID-train without attacks (`train_none.csv`, SHA-256 `{s['datasetSha256'][:16]}`), "
      f"evaluated with raid-bench {r['raidBench']}")
    w(f"- **Sample** {s['total']:,} texts: all {s['human']:,} human texts, and {s['machinePerGeneratorAndDomain']} "
      f"machine texts for each of 11 generators in each of 8 domains ({s['machine']:,}); seed {s['seed']}, "
      f"id fingerprint `{s['idFingerprintSha256'][:16]}`")
    w(f"- **Engine** SignsOfAI.Core {r['engine']} at `{commit}`, rule packs unchanged, language set to English")
    w(f"- **Run** {run_date}")
    w("- **Counted by** RAID's own `run_evaluation`, at a 5% and a 1% false-positive rate")
    w("")
    w("**How RAID counts.** It takes the raw score and finds, separately for each domain, the cutoff that flags 5% "
      "of its human texts. Then it counts how much machine text lands above that cutoff. The score is this tool's "
      "0–100 divided by 100, because RAID's search assumes a 0–1 range; dividing by a constant changes no ranking. "
      "So the product's own boundary and its length floor play no part here, and the cutoffs RAID finds are not "
      "this tool's.")
    w("")
    w("## The headline")
    w("")
    w(f"- **{pct(pd_['overall']['tpr05'])}** of machine-written text is caught at a 5% false-positive rate "
      f"({pct(pd_['overall']['tpr01'])} at 1%; AUROC {pd_['overall']['auroc']:.2f}).")
    w(f"- **Chat-tuned generators {pct(groups['chat']['tpr05'])}, base models {pct(groups['base']['tpr05'])}.** "
      f"ChatGPT alone {pct(by_model['chatgpt']['tpr05'])}. The four base models sit between "
      f"{pct(min(base_models))} and {pct(max(base_models))}, with an AUROC near 0.5: close to what a score that "
      "knew nothing would do.")
    w(f"- **As shipped, the product would have answered none of them.** No machine-written text in RAID reaches "
      f"{prod['lengthFloorWords']} words, the shortest text the published false-positive rate was measured on, and "
      "below that length the product withholds its verdict (#59).")
    w("")
    w("This is far below the commercial detectors at the top of RAID's leaderboard. It is also what this project has "
      "said from the start. The tells are evidence about how a text reads, and most of them are fingerprints of "
      "chat-tuning. They are not a way to tell who wrote it.")
    w("")
    w("## What we predicted, and what happened")
    w("")
    w("Written and committed before any RAID text was scored ([prediction.md](Detection/prediction.md), commit "
      "`e007adc`). Each line is judged by the refutation criterion it was written with.")
    w("")
    w("| # | Prediction | Measured | Result |")
    w("|---|---|---|---|")
    w(f"| P1 | Chat-tuned rate at least twice the base-model rate | chat {pct(groups['chat']['tpr05'])}, "
      f"base {pct(groups['base']['tpr05'])}, ratio {groups['chat']['tpr05'] / groups['base']['tpr05']:.2f} | "
      f"{'held' if preds['P1']['held'] else '**failed**'} |")
    w(f"| P2 | Base-model rate under 20% | {pct(groups['base']['tpr05'])} | {'held' if preds['P2']['held'] else '**failed**'} |")
    w(f"| P3 | text-davinci-003 between the two groups | {pct(groups['between']['tpr05'])} | "
      f"{'held' if preds['P3']['held'] else '**failed**'} |")
    top3 = sorted(pd_["byDomain"].items(), key=lambda x: -x[1]["tpr05"])[:3]
    w(f"| P4 | Poetry and recipes not among the three best domains | best three: "
      f"{', '.join(f'{DOMAINS[d]} {pct(v['tpr05'])}' for d, v in top3)} | "
      f"{'held' if preds['P4']['held'] else '**failed**'} |")
    hg, zw = attacks["homoglyph"], attacks["zero_width_space"]
    h_alarm = a["unattackedHumanScan"]
    p5 = hg["scanMachine"]["strong"] >= 0.99 and zw["scanMachine"]["strong"] >= 0.99 and h_alarm["any"] <= 0.01
    w(f"| P5 | Scanner catches at least 99% of homoglyph and zero-width attacks, with false alarms on at most 1% of "
      f"human texts | homoglyph {pct(hg['scanMachine']['strong'])}, zero-width {pct(zw['scanMachine']['strong'])}; "
      f"false alarms {pct(h_alarm['any'], 2)} | {'held' if p5 else '**failed**'} |")
    p6 = hg["meanScoreAfter"] < hg["meanScoreBefore"]
    w(f"| P6 | The homoglyph attack lowers the score | mean {hg['meanScoreBefore']:.1f} → {hg['meanScoreAfter']:.1f}; "
      f"caught {pct(hg['tprBefore'])} → {pct(hg['tprAfter'])} | {'held by its letter, failed in substance' if p6 else '**failed**'} |")
    w(f"| — | Between 15% and 40% overall, without attacks | {pct(pd_['overall']['tpr05'])} | "
      f"{'held' if preds['overall']['held'] else '**failed**'} |")
    w("")
    if poetry_burst:
        w(f"**P4 failed** because machine verse settles into lines of even length: `stat.burstiness` fires on "
          f"{pct(poetry_burst['machine'], 0)} of machine poems and {pct(poetry_burst['human'], 0)} of human ones. "
          f"Recipes were as weak as predicted ({pct(pd_['byDomain']['recipes']['tpr05'])}), because they are "
          "formulaic whoever writes them.")
        w("")
    w(f"**P6 held by its letter and failed in substance.** The score did drop, by "
      f"{hg['meanScoreBefore'] - hg['meanScoreAfter']:.2f} points on average across the machine texts. The note "
      "added to the prediction before measuring was closer: the analyzer restores disguised letters before any "
      "rule reads the text. What the attack still moves is explained under *Attacks* below.")
    w("")
    w("## By generator")
    w("")
    w("| Generator | Kind | Caught at 5% | Caught at 1% | AUROC |")
    w("|---|---|---|---|---|")
    for m, v in sorted(by_model.items(), key=lambda x: -x[1]["tpr05"]):
        w(f"| {NAMES[m]} | {GROUP[m]} | {pct(v['tpr05'])} | {pct(v['tpr01'])} | {v['auroc']:.2f} |")
    w("")
    below = [NAMES[m] for m, v in by_model.items() if v["auroc"] < 0.5]
    if below:
        w(f"An AUROC below 0.5 ({', '.join(below)}) means that generator's text scores, on average, as *less* "
          "machine-like than the human text it is compared with.")
        w("")
    w("## By domain")
    w("")
    w("| Domain | Caught at 5% | AUROC | Lowest score counted |")
    w("|---|---|---|---|")
    low = pd_["lowestCounted"]
    for d, v in sorted(pd_["byDomain"].items(), key=lambda x: -x[1]["tpr05"]):
        w(f"| {DOMAINS[d]} | {pct(v['tpr05'])} | {v['auroc']:.2f} | {low[d]:.1f} |")
    w("")
    w("The engine scores to one decimal and RAID's cutoffs fall between those steps, so the last column gives the "
      "lowest score each cutoff counts rather than the cutoff rounded: rounding can carry a whole tie across it. "
      "The exact cutoffs are in `Docs/Detection/results.json`.")
    w("")
    md, mr = r["matchedDecoding"], r["matchedRepetitionPenalty"]
    w(f"Greedy decoding is caught more often than sampling ({pct(md['greedy']['tpr05'])} against "
      f"{pct(md['sampling']['tpr05'])}, across all {len(md['models'])} generators). Only {len(mr['models'])} "
      f"generators were run both with and without a repetition penalty; across those, texts generated with it are "
      f"caught {pct(mr['yes']['tpr05'])} of the time and texts without it {pct(mr['no']['tpr05'])}. These are "
      "observed differences between settings, not controlled experiments, and what causes them was not measured.")
    w("")
    w(f"With one cutoff for every domain, closer to how the product works, the rate is "
      f"{pct(single['overall']['tpr05'])} (lowest score counted {single['lowestCounted']:.1f}).")
    w("")
    w("## Found along the way")
    w("")
    w("None of what follows was predicted. It is reported because it is true, and it should be read as "
      "observation rather than as a test that could have failed.")
    w("")
    w("### The product's boundary on short text")
    w("")
    w(f"RAID's texts are short: the median human text has {prod['medianWords']['human']:.0f} words and the median "
      f"machine text {prod['medianWords']['machine']:.0f}. At the product's boundary of {prod['boundary']}/100, "
      f"ignoring the length floor, **{pct(prod['ignoringFloor']['fpr'])} of RAID's human texts would be flagged**, "
      f"against {pct(prod['ignoringFloor']['tpr'])} of the machine ones. That is the reason for the floor: below the "
      "lengths the boundary was measured on, it would accuse roughly one person in nine.")
    w("")
    w("| Length | Human texts | Machine texts | Human flagged at RAID's cutoff | Machine caught |")
    w("|---|---|---|---|---|")
    for b in r["byLength"]:
        w(f"| {b['bucket']} words | {b['human']:,} | {b['machine']:,} | {pct(b['fpr05'])} | {pct(b['tpr05'])} |")
    w("")
    w(f"Only {pct(prod['shareAtOrAboveFloor']['human'])} of the human texts and none of the machine texts reach "
      f"{prod['lengthFloorWords']} words.")
    w("")
    w("### Long human writing the calibration does not contain")
    w("")
    w(f"{lh['texts']} distinct human texts in the sample reach the floor ({lh['rows']} rows: RAID repeats a few "
      "texts verbatim, and here each is counted once). They are an outside sample of long human writing, but "
      "of a different population from the calibration corpus, which holds research articles, encyclopedia "
      "revisions and learner essays. These are news articles, book summaries, film reviews and verse. At the "
      f"product's boundary of {prod['boundary']}/100:")
    w("")
    w("| Domain | Texts | Crossing the boundary | 95% interval |")
    w("|---|---|---|---|")
    for d, v in sorted(lh["byDomain"].items(), key=lambda x: -x[1]["flagged"]):
        w(f"| {DOMAINS[d]} | {v['texts']} | {v['flagged']} | {interval(v['interval'])} |")
    w(f"| **all** | **{lh['texts']}** | **{lh['flagged']}** | **{interval(lh['interval'])}** |")
    w("")
    pub = lh["published"]
    news = lh["byDomain"]["news"]
    nb = lh["rulesInFlagged"].get("stat.burstiness", 0)
    w(f"Overall that is {pct(lh['rate'])}, against the published {pub['flagged']} of {pub['texts']} "
      f"({interval(pub['interval'])}). The two intervals overlap. The difference sits almost entirely in one register: "
      f"**{news['flagged']} of {news['texts']} news articles cross the boundary** ({interval(news['interval'])}), "
      "a register the calibration corpus never contained, and the point estimate is above the 5% this project "
      f"promises. {nb} of the {lh['flagged']} flagged texts carry `stat.burstiness`: news prose tends to keep its "
      "sentences to an even length, and sentence-length variation is the signal this tool trusts most.")
    w("")
    w("This does not move the published number, which describes the corpus it was measured on, and the calibration "
      "page already says a rate does not transfer from one population to another. It is the first measurement of "
      "how far it fails to transfer, and where. A teacher of a register like this one, journalism for instance, "
      "should calibrate on their own students' earlier work before trusting the boundary. "
      "Any change to the published rate goes through the calibration corpus and the review committee, not through "
      "RAID.")
    w("")
    w("### Which rules carry the signal")
    w("")
    w("Share of texts each rule fires on, for the rules that fire most often on chat-tuned text relative to human "
      "text (at least 50 texts):")
    w("")
    w("| Rule | Human | Chat-tuned | Base | Chat ÷ human |")
    w("|---|---|---|---|---|")
    for x in r["rules"][:12]:
        w(f"| `{x['rule']}` | {pct(x['human'])} | {pct(x['chat'])} | {pct(x['base'])} | {x['chatLift']:.0f}× |")
    w("")
    if burst:
        w(f"Each of them is rare: strong evidence where it appears, absent from most texts. The rule that does most "
          f"of the separating is `stat.burstiness`, which fires on {pct(burst['human'])} of human texts, "
          f"{pct(burst['chat'])} of chat-tuned ones and {pct(burst['base'])} of base-model ones. It separates "
          "chat-tuned text, and base-model text not at all.")
        w("")
    wrong = [x for x in r["rules"] if x["chatLift"] is not None and x["chatLift"] < 0.5 and x["texts"] >= 200]
    if wrong:
        w("Some rules fire more often on human text than on RAID's chat-tuned output: " +
          ", ".join(f"`{x['rule']}` ({pct(x['human'])} of human texts, {pct(x['chat'])} of chat-tuned)" for x in wrong) +
          ". RAID's generators are from 2023, and the em-dash habit is usually attributed to later models, so this "
          "dates those rules to a generation rather than showing them wrong. No rule was changed in response.")
        w("")
    w("### Attacks")
    w("")
    setup = a["setup"]
    words = {8: "Eight", 9: "Nine", 7: "Seven"}
    w(f"{words.get(len(setup['attacks']), len(setup['attacks']))} of RAID's eleven attacks need no language model. "
      f"They were run, at the strengths "
      f"RAID's own code uses, on {setup['perClass']:,} human and {setup['perClass']:,} machine texts drawn from the "
      f"sample. Paraphrase, synonym swap and perplexity misspelling need a model and were left out, and "
      "paraphrase is the attack most likely to hurt a detector built on word choice. What follows is robustness "
      "to cheap attacks, not to rewriting.")
    w("")
    w("| Attack | Strength | Caught before | Caught after | Mean score | Scanner reports a strong artifact |")
    w("|---|---|---|---|---|---|")
    for name, v in sorted(attacks.items()):
        w(f"| {name.replace('_', ' ')} | {setup['attacks'][name]} | {pct(v['tprBefore'])} | {pct(v['tprAfter'])} | "
          f"{v['meanScoreBefore']:.1f} → {v['meanScoreAfter']:.1f} | {pct(v['scanMachine']['strong'])} |")
    w("")
    w(f"The scanner reports {pct(hg['scanMachine']['strong'])} of the homoglyph texts and "
      f"{pct(zw['scanMachine']['strong'])} of the zero-width ones, counting only characters that typing does not "
      f"produce. On unattacked human texts it reports something in {pct(h_alarm['any'], 2)} (any artifact, mostly "
      f"non-breaking spaces from pasted text), a strong artifact in {pct(h_alarm['strong'], 2)}, and a systematic "
      f"pattern in {pct(h_alarm['systematic'], 2)}. The few homoglyph texts it did not report were written in Greek, "
      "where those letters are the alphabet, or were degenerate outputs with no Latin word to disguise.")
    w("")
    w("**What the homoglyph attack still moves.** The scanner counts a disguised word only when Latin letters are at "
      "least half of it, so that a Greek or Cyrillic word quoted in English is not called a disguise. RAID's attack "
      "replaces every letter it can. In words such as *crucial*, *intricate* or a capitalised *Moreover* the "
      "substitutes become the majority, and a one-letter word such as *a* has no Latin letter left at all. Those "
      "words are neither reported nor restored, so the rules that need them miss, while the document as a whole is "
      "still reported. Closing this is a change of behaviour, so it was not made here: it needs its own measurement "
      "against human text, because a lone Greek or Cyrillic letter is sometimes exactly what the writer meant.")
    w("")
    w("### For scale: RAID's leaderboard")
    w("")
    w(f"Measured by RAID's authors on RAID-test (leaderboard read at commit `{lb['commit'][:7]}`). These are "
      "different texts from the same distribution, so they set a scale and are not rows in the same table as the "
      "numbers above. Nothing from this project has been submitted.")
    w("")
    w("| Detector | No attack | Homoglyph | Zero-width | Whitespace |")
    w("|---|---|---|---|---|")
    for d in lb["detectors"]:
        if d["submittedBy"] != "RAID authors":
            continue
        t = d["tpr05"]
        w(f"| {d['name']} | {pct(t['none'])} | {pct(t['homoglyph'])} | {pct(t['zero_width_space'])} | {pct(t['whitespace'])} |")
    w("")
    vendors = [d["tpr05"]["none"] for d in lb["detectors"] if d["submittedBy"] == "vendor"]
    if vendors:
        w(f"Entries submitted by their vendors sit between {pct(min(vendors))} and {pct(max(vendors))}. RAID's "
          "training half is public, so a high score shows that a detector separates this dataset. It does not show "
          "how the detector does on other text. That is a fact about how the benchmark is built, not a claim about "
          "any detector.")
        w("")
    w("Under the zero-width attack some detectors rise to about 98%. That is credit for detecting the attack, not "
      "the author: RAID sets its cutoff on unattacked human text only, so a human file carrying the same invisible "
      "characters is never counted against them. This tool reports those characters as a fact about the file and "
      "keeps them out of the score, which is why its score does not move.")
    w("")
    w("## Where this departs from the plan")
    w("")
    w(f"- **All {s['human']:,} human texts** were used instead of 500 per domain. More human text makes the cutoff "
      "steadier, and it cannot be tuned in anyone's favour.")
    dn = r["detectedNotEnglish"]
    w(f"- **Language fixed to English**, as the calibration does. The web app detects the language instead and would "
      f"have misread {pct(dn['human'])} of the human texts and {pct(dn['machine'])} of the machine ones.")
    w("- **Scores divided by 100** for RAID's threshold search, which assumes a 0–1 range.")
    w("- **Both cutoffs reported**: RAID's per-domain cutoff first, then one cutoff for all domains.")
    ht = r["humanTexts"]
    w(f"- **Repeated texts.** RAID-train's human set holds {ht['distinct']:,} distinct texts in {ht['rows']:,} rows. "
      "The headline counts rows, as RAID does; the long-text check above counts each distinct text once.")
    w("")
    w("## What this does not tell you")
    w("")
    w("- **Anything about current models.** RAID's generators are from 2023. Newer models write differently and the "
      "tells move with them. The right response to \"a newer model writes differently\" is to measure it.")
    w("- **A leaderboard result.** This is a sample of RAID-train, not RAID-test, and nothing has been submitted.")
    w("- **Anything about students.** RAID's human texts are published writing. The effect on second-language "
      "learners (#75) is invisible here, which is what the calibration corpus is for.")
    w("- **A cutoff tuned on other text.** RAID chooses each cutoff on the same human texts it then counts against. "
      "That is its method, and it favours every detector equally.")
    w("- **Robustness to rewriting.** Paraphrase, synonym swap and misspelling were not run.")
    w("- **More than one run.** One seed, one sample. Intervals are given only where shown.")
    w("- **An independent author.** The same model that wrote the rule packs wrote these scripts and this page. The "
      "defence is that the counting is RAID's code, not ours, and that the predictions were committed first.")
    w("")
    w("## Re-run it yourself")
    w("")
    w("See [tools/raid/README.md](../tools/raid/README.md). In short: download `train_none.csv`, draw the sample with "
      "`tools/raid/sample.py`, score it with `signsofai-calibrate raid`, count it with `tools/raid/evaluate.py`, "
      "attack it with `tools/raid/attack.py`, and write this page with `tools/raid/report.py`. The id fingerprint "
      "above says whether you drew the same sample.")
    w("")
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="Docs/Detection")
    ap.add_argument("--commit", required=True, help="engine commit the scores were produced at")
    ap.add_argument("--run-date", required=True)
    ap.add_argument("--out", default="Docs/DETECTION.md")
    args = ap.parse_args()
    d = Path(args.dir)
    load = lambda n: json.loads((d / n).read_text(encoding="utf-8"))
    page = build(load("results.json"), load("attacks.json"), load("leaderboard-scale.json"), args.commit, args.run_date)
    Path(args.out).write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(page.splitlines())} lines)")


if __name__ == "__main__":
    main()

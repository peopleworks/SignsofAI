def pct(x, digits=1):
    return "n/a" if x is None else f"{x * 100:.{digits}f}%"


def interval(pair, digits=1):
    lo, hi = pair
    return f"{lo * 100:.{digits}f}–{hi * 100:.{digits}f}%"


WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten",
         11: "eleven", 12: "twelve", 13: "thirteen", 14: "fourteen", 15: "fifteen", 16: "sixteen", 20: "twenty"}


def few(x):
    """A count of people a teacher can picture, not a fraction of a student."""
    if x < 1:
        return "fewer than one"
    if x < 2:
        return "one or two"
    return f"about {round(x)}"


def times(x):
    n = round(x)
    return {2: "twice", 3: "three times", 4: "four times", 5: "five times"}.get(n, f"{n} times")



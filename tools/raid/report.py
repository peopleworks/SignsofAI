def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="Docs/Detection")
    ap.add_argument("--commit", required=True, help="engine commit the scores were produced at")
    ap.add_argument("--run-date", required=True)
    ap.add_argument("--out", default="Docs/DETECTION.md")
    args = ap.parse_args()
    d = Path(args.dir)
    load = lambda n: json.loads((d / n).read_text(encoding="utf-8"))
    page = build(load("results.json"), load("attacks.json"), load("leaderboard-scale.json"), args.commit, args.run_date)
    Path(args.out).write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(page.splitlines())} lines)")


if __name__ == "__main__":
    main()
